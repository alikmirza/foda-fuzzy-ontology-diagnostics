"""Generate the online supplement for the KES 2027 paper from committed results.

Writes docs/kes2027_supplement.md: the rule base and its fuzzy terms, graph
statistics, and the full tables behind the paper's summary tables. Every table
is read from results/ (or from the rule base in code), so the supplement cannot
drift from the data. Deterministic.

Usage:
    PYTHONPATH=. python3 scripts/make_kes_supplement.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

import evaluation.methods.foda_fcp as fcp
from scripts.run_direction_variants import CALLS_OB, CALLS_SS

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
SYSTEM = {"re1-ob": "RE1-OB", "re1-ss": "RE1-SS", "re1-tt": "RE1-TT"}
TERMS = [  # the evaluated port's fuzzifier, evaluation/methods/foda_fcp.py::_fuzzify_service
    ("cpu_LOW / memory_LOW", "|z|", "trap(0, 0, 0.5, 1)"),
    ("cpu_MEDIUM / memory_MEDIUM", "|z|", "tri(0.5, 1.5, 3)"),
    ("cpu_HIGH / memory_HIGH", "|z|", "trap(1, 3, inf, inf)"),
    ("latency_NORMAL", "max(z, 0)", "trap(0, 0, 0.5, 1)"),
    ("latency_ELEVATED", "max(z, 0)", "tri(0.5, 2, 4)"),
    ("latency_CRITICAL", "max(z, 0)", "trap(2, 4, inf, inf)"),
    ("errorRate_NONE", "max(z, 0)", "trap(0, 0, 0.3, 0.8)"),
    ("errorRate_LOW", "max(z, 0)", "tri(0.3, 1, 2)"),
    ("errorRate_ELEVATED", "max(z, 0)", "tri(1, 2, 4)"),
    ("errorRate_HIGH", "max(z, 0)", "trap(2, 4, inf, inf)"),
    ("throughput_LOW", "max(-z, 0)", "trap(0.5, 2, inf, inf)"),
    ("throughput_NORMAL", "max(-z, 0)", "1 - throughput_LOW"),
]


def md(df: pd.DataFrame, digits: int = 3) -> str:
    def cell(v):
        if isinstance(v, float):
            return "" if pd.isna(v) else f"{v:.{digits}f}"
        return str(v)
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    rule = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, rule] + body)


def main() -> int:
    out = ["# Supplement: aggregation operators and weight normalisation in fuzzy confidence propagation",
           "",
           "Generated by `scripts/make_kes_supplement.py` from the result files in `results/`; "
           "`RESULTS_PROVENANCE.md` records the commit and script behind each file. Expected AC@k is the score "
           "under random tie-breaking; AC@k without qualification uses the pessimistic tie rule. Intervals "
           "resample the 25 fault scenarios of a system (10,000 resamples, seed 42).", ""]

    out += ["## S1. Rule base", "",
            "Sixteen fuzzy rules with certainty factors. A rule's strength is its certainty factor times the "
            "minimum membership of its antecedents; a service's local evidence H is the largest strength.", ""]
    rules = pd.DataFrame([{"Rule": r.rule_id, "Antecedents": " AND ".join(r.antecedents), "Category": r.consequent,
                           "CF": f"{r.cf:.2f}", "Prototype": fcp.CATEGORY_TO_FAULT.get(r.consequent, "")}
                          for r in fcp.RULE_BASE])
    out += [md(rules), "",
            "The six rule categories map onto five of the ontology's eight fault prototypes; `CASCADING_FAILURE` "
            "and `RESOURCE_CONTENTION` share `ResourceContention`. No rule assigns `DiskIoBottleneck`, "
            "`NetworkCongestion` or `ThroughputDegradation`. The `CASCADING_FAILURE` rules are local: they fire "
            "on one service showing several symptoms at once.", ""]

    out += ["## S2. Fuzzy terms", "",
            "z is the change of a metric's post-onset mean from its pre-onset mean, in pre-onset standard "
            "deviations. trap(a, b, c, d) and tri(a, b, c) are the usual trapezoidal and triangular functions.", "",
            md(pd.DataFrame(TERMS, columns=["Term", "Argument", "Membership function"])), ""]

    g = pd.read_csv(RESULTS / "graph_stats_summary.csv")
    g["system"] = g["system"].map(SYSTEM)
    out += ["## S3. Graphs", "", "Inferred graphs (lagged correlation at threshold 0.5), per case:", "",
            md(g[["system", "n_services", "median_edges", "max_edges", "median_density", "cases_cyclic",
                  "cases_all_row_sums_le1", "median_max_row_sum", "max_max_row_sum", "median_max_out_degree"]]), "",
            "Call graphs (caller -> callee, with the call counts used for the `share` weighting). Online "
            "Boutique: requests counted by Istio over 20 minutes of a demo deployment. Sock Shop: the published "
            "architecture, with calls per request as its code makes them.", "",
            md(pd.DataFrame([{"System": "RE1-OB", "Caller": a, "Callee": b, "Calls": n} for (a, b), n in CALLS_OB.items()]
                            + [{"System": "RE1-SS", "Caller": a, "Callee": b, "Calls": n} for (a, b), n in CALLS_SS.items()]),
               digits=0), ""]

    ops = pd.read_csv(RESULTS / "kes_operators.csv")
    ops["system"] = ops["system"].map(SYSTEM)
    out += ["## S4. Every operator and weighting at damping 0.85 (inferred graph, forward direction)", "",
            "`diff_vs_local` is the difference in expected AC@1 from local evidence alone, with its 95 % interval "
            "and Holm-adjusted p-value within the system.", "",
            md(ops[["system", "operator", "weights", "ac1", "ac1_expected", "ac3", "ac5", "mrr", "avg5",
                    "avg5_expected", "saturated_per_case", "runs_at_cap", "diff_vs_local", "diff_lo", "diff_hi",
                    "p_holm"]]), ""]

    b = pd.read_csv(RESULTS / "kes_budget_vs_damping.csv"); b["system"] = b["system"].map(SYSTEM)
    lo = pd.read_csv(RESULTS / "kes_loso.csv"); lo["held_out"] = lo["held_out"].map(SYSTEM)
    out += ["## S5. Weight budget against damping", "", md(b), "",
            "Damping chosen by leave-one-system-out on expected AC@1 (probabilistic sum):", "", md(lo), ""]

    br = pd.read_csv(RESULTS / "kes_breakdown.csv"); br["system"] = br["system"].map(SYSTEM)
    out += ["## S6. Breakdowns", ""]
    for by, title in (("fault", "By injected fault type (expected AC@1)"),
                      ("root", "By root-cause service (expected AC@1)"),
                      ("rule fired at root cause", "By whether a rule fired at the root cause (expected AC@1)"),
                      ("rule fired anywhere", "By whether any rule fired in the case (expected AC@1)")):
        t = br[br.by == by].pivot_table(index=["system", "value"], columns="configuration", values="ac1_expected",
                                        sort=False).reset_index()
        n = br[(br.by == by) & (br.configuration == "local")][["system", "value", "cases"]]
        t = t.merge(n, on=["system", "value"])
        cols = ["system", "value", "cases"] + [c for c in ("local", "shipped", "normalised", "capped", "max",
                                                           "callgraph_forward", "callgraph_reversed") if c in t.columns]
        out += [f"### {title}", "", md(t[cols]), ""]

    f = pd.read_csv(RESULTS / "kes_failures.csv"); f["system"] = f["system"].map(SYSTEM)
    out += ["## S7. Where each configuration fails", "", "Cases per outcome.", "",
            md(f.pivot_table(index=["system", "configuration"], columns="category", values="cases", fill_value=0,
                             sort=False).astype(int).reset_index()), ""]

    e = pd.read_csv(RESULTS / "kes_evidence_ties.csv"); e["system"] = e["system"].map(SYSTEM)
    t = pd.read_csv(RESULTS / "kes_tie_order.csv"); t["system"] = t["system"].map(SYSTEM)
    out += ["## S8. Ties in local evidence", "", md(e), "",
            "Within the top tie block of H (ties at a non-zero value), the probability that the ground truth "
            "comes first when the block is ordered by the propagated score, against chance:", "", md(t), ""]

    s = pd.read_csv(RESULTS / "saturation_bounds_summary.csv"); s["system"] = s["system"].map(SYSTEM)
    p = pd.read_csv(RESULTS / "saturation_predictors.csv"); p["system"] = p["system"].map(SYSTEM)
    out += ["## S9. Saturation brackets", "",
            "Cases with a saturated tie (at least two services at C >= 1 - 1e-12) and services saturated: "
            "guaranteed by the sufficient side, observed, and allowed by the necessary side.", "", md(s), "",
            "The necessary bound, the out-degree and the weight sum as predictors of which services saturate "
            "(area under the ROC curve), and the bound as a yes/no rule, at damping 0.85:", "",
            md(p[p.delta == 0.85].drop(columns=["delta"]), digits=4), ""]

    d = pd.read_csv(RESULTS / "direction_variants_tests.csv"); d["system"] = d["system"].map(SYSTEM)
    c = pd.read_csv(RESULTS / "direction_variants_summary.csv")
    c = c[(c.graph == "callgraph") & (c.operator == "probsum") & (c.guidance == "none")].copy()
    c["system"] = c["system"].map(SYSTEM)
    sel = pd.read_csv(RESULTS / "direction_variants_callgraph_selection.csv")
    out += ["## S10. Direction of propagation and call graphs", "",
            "Probabilistic sum at damping 0.85, no guidance, against local evidence (expected AC@1):", "",
            md(d[(d.comparison == "vs local") & (d.metric == "ac1_expected")]
               .drop(columns=["comparison", "metric"])), "",
            "Ontology guidance against no guidance (expected AC@1):", "",
            md(d[(d.comparison != "vs local") & (d.metric == "ac1_expected")].drop(columns=["metric"])), "",
            "Call graphs, probabilistic sum, expected AC@1 by damping:", "",
            md(c.pivot_table(index=["system", "direction", "weights"], columns="delta", values="ac1_expected",
                             sort=False).reset_index()), "",
            "Configuration chosen on one application and scored on the other:", "", md(sel, digits=4), ""]

    x = pd.read_csv(RESULTS / "kes_explanations.csv"); x["system"] = x["system"].map(SYSTEM)
    out += ["## S11. Explanations", "",
            "`type_match` is the share of cases in which the fault prototype named for the top-ranked service "
            "matches the injected fault (`typeable`: CPU, memory and delay faults, the ones the rule base can "
            "name). SC and EC are split by whether that prototype comes from a fired rule or not.", "", md(x), ""]

    bl = pd.read_csv(RESULTS / "kes_baselines.csv"); bl["system"] = bl["system"].map(SYSTEM)
    out += ["## S12. Context: other rankers on the same cases", "",
            "Re-implementations under the same contract (injection time withheld); they are not the published "
            "figures. `ac1_diff_vs_local` compares pessimistic AC@1 with FCP's local evidence.", "", md(bl), ""]

    dst = ROOT / "docs" / "kes2027_supplement.md"
    dst.parent.mkdir(exist_ok=True)
    dst.write_text("\n".join(out))
    print("wrote", dst, f"({len(out)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
